vim.keymap.set("n", "<leader>ke", vim.diagnostic.open_float, { desc = "Show diagnostic" })
vim.keymap.set({ "n", "x" }, "<leader>ka", vim.lsp.buf.code_action, { desc = "Code action" })
vim.keymap.set("n", "<leader>kl", function()
	vim.diagnostic.setqflist()
	vim.cmd("copen")
end, { silent = true, desc = "Diagnostics to quickfix" })
